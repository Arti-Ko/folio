import Foundation

struct SeedFile: Sendable {
    let path: String
    let contents: String
}

/// Стартовое содержимое нового пространства.
enum SpaceContent {
    static func files(kind: SpaceKind, spaceName: String, now: Date) -> [SeedFile] {
        let common = [
            SeedFile(path: ".gitignore", contents: ".DS_Store\n"),
            SeedFile(path: "CLAUDE.md", contents: guide(spaceName: spaceName, kind: kind)),
            SeedFile(path: "index.md", contents: page(title: spaceName, now: now, body: homeBody(kind: kind))),
            SeedFile(path: "_Шаблоны/Страница.md", contents: ""),
            SeedFile(path: "_Входящие/README.md", contents: inboxReadme),
        ]
        let reference = SeedFile(
            path: "Справка по разметке/index.md",
            contents: page(
                title: "Справка по разметке",
                now: now,
                extra: ["status: Готово", "labels: [справка]", "order: 1000"],
                body: referenceBody(spaceName: spaceName)
            )
        )
        switch kind {
        case .work:
            return common + [
                SeedFile(path: "_Шаблоны/Протокол встречи.md", contents: meetingTemplate),
                SeedFile(path: "_Шаблоны/Требования.md", contents: requirementsTemplate),
                SeedFile(path: "_Шаблоны/Техническое задание.md", contents: specificationTemplate),
                reference,
            ]
        case .personal:
            return common + [SeedFile(path: "_Шаблоны/Заметка.md", contents: noteTemplate), reference]
        case .blank:
            return common
        }
    }

    private static func page(title: String, now: Date, extra: [String] = [], body: String) -> String {
        let lines = [
            "id: \(PageID.make())",
            "title: \(FrontmatterWriter.scalar(title))",
            "created: \(DateText.iso(now))",
        ] + extra
        return FrontmatterWriter.document(frontmatterLines: lines, body: body)
    }

    private static func homeBody(kind: SpaceKind) -> String {
        switch kind {
        case .work:
            #"""
            :::info {title="Рабочее пространство"}

            Протоколы встреч, требования и технические задания. Сырьё для разбора — скриншоты Confluence и расшифровки звонков — складывай в папку `_Входящие` в корне пространства.

            :::

            [children]
            """#
        case .personal:
            #"""
            :::note {title="Личное пространство"}

            Заметки, идеи и всё, что не относится к работе.

            :::

            [children]
            """#
        case .blank:
            "[children]"
        }
    }

    private static let inboxReadme = #"""
        # Входящие

        Сюда складываются материалы для разбора: скриншоты страниц Confluence, расшифровки звонков, выгрузки.
        Эта папка не показывается в дереве страниц. После разбора исходник переносится вложением на созданную страницу.
        """#

    // MARK: - Инструкция для Claude

    private static func guide(spaceName: String, kind: SpaceKind) -> String {
        let workRules = kind == .work ? workGuide : ""
        return #"""
            # Пространство Folio «\#(spaceName)»

            Это пространство вики Folio — локального аналога Confluence. Страницы — Markdown-файлы; приложение Folio показывает и редактирует их, утилита `folio` помогает работать из терминала. Правила ниже обязательны: приложение и утилита на них опираются.

            ## Устройство

            - Страница — папка с файлом `index.md`. Подстраницы — вложенные папки со своим `index.md`.
            - `index.md` в корне — главная страница пространства, её заголовок совпадает с именем пространства.
            - Вложения (картинки, PDF) лежат в папке страницы рядом с `index.md`, ссылки на них относительные: `![Схема](схема.png)`.
            - Папки на `_` и `.` служебные и в дереве не видны: `_Шаблоны/` — шаблоны страниц, `_Входящие/` — сырьё для разбора.
            - Папка без `index.md` страницей не считается.

            ## Шапка страницы

            ```yaml
            ---
            id: 3f9c2a7b1d04          # выдаёт folio new, не менять
            title: Протокол встречи   # уникален в пространстве
            created: 2026-09-15
            status: В работе          # необязательно
            labels: [встреча, crm]    # необязательно
            order: 10                 # необязательно: порядок среди соседей
            ---
            ```

            Цвет статуса подбирается по названию: Черновик — серый, В работе — синий, На согласовании — жёлтый, Утверждено и Готово — зелёный, Отклонено — красный, Архив — фиолетовый. Другой цвет: `status_color: blue` (grey, blue, green, yellow, red, purple).

            ## Разметка

            Markdown в стиле GitHub плюс элементы Confluence:

            - Панели `:::info`, `:::note`, `:::success`, `:::warning`, `:::error`, с заголовком — `:::warning {title="Внимание"}`. Закрываются отдельной строкой `:::`, содержимое отделяется пустыми строками.
            - Раскрывающийся блок: `:::expand {title="Полная расшифровка"}` … `:::`.
            - Статус в тексте: `[status color="green"]Утверждено[/status]`; без `color` статус серый.
            - Ссылка на страницу: `[[Заголовок]]`, с другим текстом — `[[Заголовок|текст]]`, в другое пространство — `[[Личное::Заголовок]]`.
            - Оглавление — строка `[toc]`, список дочерних страниц — строка `[children]`.
            - Задачи: `- [ ] Сделать`, `- [x] Сделано`.

            Стиль, в котором сохраняет редактор (пиши так же, тогда в истории видны только настоящие правки): заголовки `#`, маркеры списков `-`, жирный `**`, курсив `*`, между блоками одна пустая строка, столбцы таблиц выровнены пробелами по самой длинной ячейке.

            ## Утилита folio

            Внутри папки пространства `--space` можно не указывать.

            - `folio tree` — дерево страниц, `folio search "запрос"` — поиск, `folio path "Заголовок"` — путь к файлу.
            - `folio open "Заголовок"` — открыть страницу в приложении Folio, чтобы показать результат.
            - `folio new "Заголовок" --parent "Родитель" --template "Протокол встречи"` — новая страница, печатает путь к `index.md`.
            - `folio rename "Старый" "Новый"` — переименование с починкой ссылок во всех пространствах.
            - `folio move "Заголовок" --parent "Новый родитель"` — перенос. Родитель верхнего уровня — главная, её заголовок равен имени пространства.
            - `folio backlinks "Заголовок"`, `folio history "Заголовок"` — кто ссылается и история правок.
            - `folio check` — дубли заголовков, битые ссылки и вложения.
            - `folio commit -m "что сделано"` — сохранить снимок в истории.

            ## Правила работы

            - Страницы создавай через `folio new`, переименовывай и переноси через `folio rename` и `folio move`, а не руками: так остаются целы шапки и ссылки.
            - Заголовки уникальны в пространстве; символы `[ ] |` и `::` в заголовках запрещены.
            - После пачки правок запускай `folio check`, затем `folio commit -m "..."` с понятным описанием.
            \#(workRules)
            """#
    }

    private static let workGuide = #"""

        ## Рабочие материалы

        - Протокол встречи — по шаблону «Протокол встречи»: участники, решения, задачи с ответственными и сроками, открытые вопросы, прозвучавшие требования. Полная расшифровка — в `:::expand {title="Расшифровка"}` в конце.
        - Требования нумеруются FR-1, NFR-1; номера не переиспользуются, даже если требование удалено.
        - Страница, восстановленная со скриншота Confluence, повторяет его структуру: заголовки, таблицы, панели, статусы. Исходный скриншот лежит вложением в папке страницы и подключается внизу в `:::expand {title="Исходник"}`.
        """#

    // MARK: - Шаблоны

    private static let meetingTemplate = #"""
        ---
        status: Черновик
        labels: [встреча]
        ---

        **Дата:** {{date}}

        **Участники:** перечисли участников

        [toc]

        ## Повестка

        - Вопрос повестки

        ## Решения

        | №   | Решение       | Кто принял |
        | --- | ------------- | ---------- |
        | 1   | Текст решения | Имя        |

        ## Задачи

        - [ ] Задача — ответственный, срок

        ## Открытые вопросы

        :::warning {title="Нужно выяснить"}

        - Вопрос — у кого узнать

        :::

        ## Прозвучавшие требования

        - Требование — кто озвучил

        :::expand {title="Расшифровка"}

        Вставь сюда расшифровку звонка.

        :::
        """#

    private static let requirementsTemplate = #"""
        ---
        status: Черновик
        labels: [требования]
        ---

        [toc]

        ## Контекст

        Какую проблему решаем и для кого.

        ## Цели и метрики успеха

