    private static let noteTemplate = #"""
        ---
        labels: [заметка]
        ---

        Текст заметки.
        """#

    // MARK: - Справка

    private static func referenceBody(spaceName: String) -> String {
        #"""
        Эта страница показывает все элементы, которые понимает Folio. Её можно удалить.

        [toc]

        ## Панели

        :::info {title="Информация"}

        Контекст или подсказка.

        :::

        :::note

        Заметка без заголовка.

        :::

        :::success {title="Решено"}

        Решение принято и зафиксировано.

        :::

        :::warning {title="Внимание"}

        Риск или ограничение.

        :::

        :::error {title="Ошибка"}

        Что-то сломано и требует действий.

        :::

        ## Статусы

        [status]Черновик[/status] [status color="blue"]В работе[/status] [status color="yellow"]На согласовании[/status] [status color="green"]Утверждено[/status] [status color="red"]Отклонено[/status] [status color="purple"]Архив[/status]

        ## Ссылки

        На главную: [[\#(spaceName)]]. Если страницы с таким заголовком нет, ссылка подсвечивается красным.

        ## Таблица

        | ID   | Требование              | Статус                                 |
        | ---- | ----------------------- | -------------------------------------- |
        | FR-1 | Вход по номеру телефона | [status color="green"]Готово[/status]  |
        | FR-2 | Выгрузка отчёта в Excel | [status color="blue"]В работе[/status] |

        ## Задачи

        - [x] Созвониться с заказчиком
        - [ ] Согласовать требования

        ## Раскрывающийся блок

        :::expand {title="Показать подробности"}

        Скрытый текст: длинные расшифровки, исходники, логи.

        :::

        ## Код и цитата

        ```sql
        select count(*) from orders where status = 'paid';
        ```

        > Цитата выглядит так.
        """#
    }
}
